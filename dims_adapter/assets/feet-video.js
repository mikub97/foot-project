/* Foot-pressure view in place of the video component — GAIT-attempt.
 *
 * A video component is a function from a timestamp to a picture. So is a
 * pressure map. This study has no camera behind it: the recordings come from
 * eight force sensors under each insole, so there is nothing to play, but there
 * is something to *see* at every instant the playhead can land on.
 *
 * It overrides `updateVideos` through the documented `DIMS.extendHost` seam
 * rather than reaching into the host, and it uses the two containers the host
 * already owns:
 *
 *   #fullVideoContainer     -> the two feet, loaded at the current playhead
 *   #segmentVideoContainer  -> who this participant is
 *
 * The geometry, the outline path and the colour ramp all arrive in the asset,
 * generated by the same Python that draws the original dashboard, so the two
 * renderings cannot drift apart.
 */
(function () {
    'use strict';

    const cache = new Map();

    function videoIDFrom(app) {
        return app && app.currentVideoID ? app.currentVideoID : null;
    }

    async function feetFor(app, videoID) {
        if (cache.has(videoID)) return cache.get(videoID);
        const promise = app.loadJSON(`assets/feet/${videoID}_feet.json`)
            .catch(() => null);
        cache.set(videoID, promise);
        return promise;
    }

    /* Nearest sample at or before `time`. Binary search: the series is 3 000
     * points and this runs on every playhead move. */
    function indexAt(times, time) {
        if (!times.length) return -1;
        let lo = 0, hi = times.length - 1;
        if (time <= times[0]) return 0;
        if (time >= times[hi]) return hi;
        while (lo < hi) {
            const mid = (lo + hi + 1) >> 1;
            if (times[mid] <= time) lo = mid; else hi = mid - 1;
        }
        return lo;
    }

    function hexToRGB(hex) {
        const n = parseInt(hex.slice(1), 16);
        return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
    }

    /* The sequential ramp, interpolated. Light means high, as in the original. */
    function rampColor(scale, fraction) {
        const f = Math.max(0, Math.min(1, fraction));
        for (let i = 1; i < scale.length; i++) {
            if (f <= scale[i][0]) {
                const [s0, c0] = scale[i - 1], [s1, c1] = scale[i];
                const k = s1 === s0 ? 0 : (f - s0) / (s1 - s0);
                const a = hexToRGB(c0), b = hexToRGB(c1);
                const mix = a.map((v, j) => Math.round(v + k * (b[j] - v)));
                return `rgb(${mix.join(',')})`;
            }
        }
        return scale[scale.length - 1][1];
    }

    function centreOfPressure(data, names, index) {
        let sum = 0, x = 0, y = 0;
        for (const name of names) {
            const w = data.sensors[name][index];
            if (!(w > 0)) continue;
            sum += w;
            x += w * data.coords[name][0];
            y += w * data.coords[name][1];
        }
        return sum > 0 ? [x / sum, y / sum] : null;
    }

    function feetSVG(data, index, time) {
        const [vx, , vw] = data.viewBox;
        const parts = [];

        for (const path of data.outlines) {
            parts.push(`<path d="${path}" fill="#262625" stroke="#383835" stroke-width="8"/>`);
        }

        const names = data.left.concat(data.right);
        for (const name of names) {
            const value = data.sensors[name][index];
            const f = data.peak > 0 ? value / data.peak : 0;
            const [x, y] = data.coords[name];
            parts.push(
                `<circle cx="${x}" cy="${y}" r="${45 + 85 * Math.max(0, Math.min(1, f))}" ` +
                `fill="${rampColor(data.scale, f)}" stroke="#1E1E1E" stroke-width="12"><title>${name}: ${value.toFixed(0)} N</title></circle>`
            );
        }

        for (const [side, names_, colour] of [
            ['Left', data.left, data.colors.left],
            ['Right', data.right, data.colors.right],
        ]) {
            const cop = centreOfPressure(data, names_, index);
            if (cop) {
                parts.push(
                    `<circle cx="${cop[0]}" cy="${cop[1]}" r="115" fill="none" ` +
                    `stroke="${colour}" stroke-width="20"><title>${side} centre of pressure</title></circle>`
                );
            }
        }

        parts.push(`<text x="-500" y="1210" text-anchor="middle" fill="${data.colors.left}" font-size="110" transform="scale(1,-1)">Left</text>`);
        parts.push(`<text x="500" y="1210" text-anchor="middle" fill="${data.colors.right}" font-size="110" transform="scale(1,-1)">Right</text>`);

        return `
          <h3 style="color:var(--text,#fff);margin:0 0 4px;font-size:15px;">Foot pressure</h3>
          <div style="color:#898781;font-size:11px;margin-bottom:6px;">
            t = ${time.toFixed(2)} s · ○ centre of pressure · colour and size = force, scale fixed to this recording's peak (${data.peak.toFixed(0)} N)
          </div>
          <svg viewBox="${vx} -1200 ${vw} 2450" style="width:100%;max-height:460px;display:block;">
            <g transform="scale(1,-1)">${parts.join('')}</g>
          </svg>`;
    }

    function demographicsHTML(data, startTime, endTime) {
        const rows = data.demographics.map(
            (r) => `<tr><td style="color:#898781;padding:2px 10px 2px 0;white-space:nowrap;">${r.label}</td>` +
                   `<td style="color:var(--text,#fff);padding:2px 0;">${r.value}</td></tr>`
        ).join('');
        const window_ = Number.isFinite(startTime) && Number.isFinite(endTime)
            ? `${startTime.toFixed(1)}–${endTime.toFixed(1)} s`
            : 'whole recording';
        return `
          <h3 style="color:var(--text,#fff);margin:0 0 4px;font-size:15px;">Participant</h3>
          <div style="color:#898781;font-size:11px;margin-bottom:6px;">${data.subject} · window ${window_}</div>
          <table style="font-size:12px;border-collapse:collapse;">${rows}</table>
          <div style="color:#898781;font-size:10px;margin-top:10px;line-height:1.4;">
            Clinical scores are published with the dataset. Stride time and
            stride-time variability are <em>derived</em> from the force signal,
            not measured.
          </div>`;
    }

    window.DIMS.extendHost({
        async updateVideos(clickTime, windowSize) {
            const videoID = videoIDFrom(this);
            const full = document.getElementById('fullVideoContainer');
            const segment = document.getElementById('segmentVideoContainer');
            if (!videoID || !full) return;

            const data = await feetFor(this, videoID);
            if (!data) {
                full.innerHTML = '<p style="color:#898781;">No foot-pressure asset for this recording.</p>';
                if (segment) segment.innerHTML = '';
                return;
            }

            /* The host calls this once before any click, with no playhead. The
             * start of the recording is the honest answer, not NaN. */
            const time = Number.isFinite(clickTime) ? clickTime : data.t[0];
            const half = Number.isFinite(windowSize) ? windowSize / 2 : NaN;

            full.innerHTML = feetSVG(data, indexAt(data.t, time), time);
            if (segment) {
                segment.innerHTML = demographicsHTML(
                    data, Math.max(0, time - half), time + half
                );
            }
        },
    });
})();
